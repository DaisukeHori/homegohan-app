/**
 * scripts/lib/shell-quote-arg.mjs — 値を、POSIX シェルの 1 語として安全に渡せる形にする (#1444)。
 *
 * 単一引用符で囲み、中の ' は '\'' (引用を閉じる → エスケープした ' → 引用を開き直す) にする。
 * 単一引用符の中では $ ` \ " なども特別な意味を持たないので、どんな文字列でも 1 語のまま、そのままの値で渡る。
 * コマンドの文字列にどうしてもシェルを通す必要があるとき (at のジョブの本文など) だけに使う。
 * 引数で渡せるなら、シェルを通さない (spawn / execFile に配列で渡す) ほうを選ぶ。
 */
export function quoteShellArg(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}
